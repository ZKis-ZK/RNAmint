#!/usr/bin/env python3
"""Keep README.md and sitemap.xml in step with the site.

Run automatically by .githooks/pre-commit before every commit, or by hand:
    python3 .githooks/update_docs.py

- Rewrites the block between the AUTO markers in README.md with a summary
  generated from the pages (pages, current grants, current team).
- Sets <lastmod> in sitemap.xml to today for any page being committed.
- When styles.css is committed, updates the ?v= version on each page's stylesheet link.
"""
import datetime
import hashlib
import html
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TODAY = datetime.date.today().isoformat()

PAGES = [  # (file, public URL, in sitemap)
    ("index.html",          "https://rnamint.com/",          True),
    ("research/index.html", "https://rnamint.com/research/", True),
    ("team/index.html",     "https://rnamint.com/team/",     True),
    ("contact/index.html",  "https://rnamint.com/contact/",  True),
    ("zoltan/index.html",   "https://rnamint.com/zoltan/",   False),
    ("404.html",            "https://rnamint.com/404.html",  False),
]

START = "<!-- AUTO:START (generated by .githooks/update_docs.py — do not edit by hand) -->"
END = "<!-- AUTO:END -->"


def git(*args):
    return subprocess.run(["git", *args], cwd=ROOT, capture_output=True, text=True).stdout.strip()


def text(fragment):
    fragment = re.sub(r"<sup>\s*TM\s*</sup>", "™", fragment)
    return html.unescape(re.sub(r"\s+", " ", re.sub(r"<[^>]+>", " ", fragment))).strip()


def staged_files():
    return set(git("diff", "--cached", "--name-only").splitlines())


def last_changed(path, staged):
    if path in staged:
        return TODAY
    return git("log", "-1", "--format=%ad", "--date=short", "--", path) or "—"


def grants_summary(lines):
    s = (ROOT / "research/index.html").read_text()
    rows = re.findall(r'<tr data-start="([\d-]+)" data-end="([\d-]+)">(.*?)</tr>', s, re.S)
    bars = re.findall(r'class="tl-bar[^"]*"\s+data-start="[\d-]+" data-end="([\d-]+)"', s)
    cur_html = s[s.index('id="grants-current"'):s.index('id="grants-previous"')]
    current = [r for r in rows if r[1] >= TODAY]
    active_bars = sum(1 for e in bars if e >= TODAY[:7])

    lines.append(f"### Current grants ({len(current)}) — as shown to visitors today")
    lines.append("")
    lines.append("| Ends | Funder | Title |")
    lines.append("|---|---|---|")
    for start, end, body in sorted(current, key=lambda r: r[1]):
        cells = re.findall(r"<td[^>]*>(.*?)</td>", body, re.S)
        funder = text(re.sub(r"<small>.*?</small>", "", cells[1], flags=re.S))
        title = text(cells[3])
        title = title if len(title) <= 90 else title[:87] + "…"
        lines.append(f"| {end} | {funder} | {title} |")
    lines.append("")

    notes = []
    stale = [r for r in rows if r[1] < TODAY and f'data-end="{r[1]}"' in cur_html]
    if stale:
        notes.append(f"{len(stale)} ended grant(s) still sit under Current grants in the HTML. "
                     "The page moves them automatically for visitors, but you may want to move the rows "
                     "to Previous grants in `research/index.html`.")
    if len(bars) != len(rows):
        notes.append(f"The timeline has {len(bars)} bars but the tables have {len(rows)} grants — "
                     "a grant may be missing from one of them.")
    if active_bars != len(current):
        notes.append(f"The Active grants counter (timeline) shows {active_bars}, but {len(current)} grants are current "
                     "in the tables — check the end dates match.")
    for n in notes:
        lines.append(f"> ⚠️ {n}")
    if notes:
        lines.append("")


def team_summary(lines):
    s = (ROOT / "team/index.html").read_text()
    s = s[:s.index("<h2>Alumni</h2>")]
    people = [text(h) for h in re.findall(r'<div class="person-details">\s*<h2>(.*?)</h2>', s, re.S)]
    lines.append(f"### Current team on the team page ({len(people)})")
    lines.append("")
    lines += [f"- {p}" for p in people]
    lines.append("")


def update_readme(staged):
    readme = ROOT / "README.md"
    content = readme.read_text()
    if START not in content or END not in content:
        print("update_docs: AUTO markers missing from README.md — skipped", file=sys.stderr)
        return
    lines = [START, "", f"_Last generated: {TODAY}_", "", "### Pages", "",
             "| Page | File | Last changed | In sitemap |", "|---|---|---|---|"]
    for path, url, in_sitemap in PAGES:
        lines.append(f"| {url} | `{path}` | {last_changed(path, staged)} | {'yes' if in_sitemap else 'no'} |")
    lines.append("")
    grants_summary(lines)
    team_summary(lines)
    lines.append(END)
    new = content[:content.index(START)] + "\n".join(lines) + content[content.index(END) + len(END):]
    if new != content:
        readme.write_text(new)


def update_sitemap(staged):
    sitemap = ROOT / "sitemap.xml"
    s = sitemap.read_text()
    for path, url, in_sitemap in PAGES:
        if in_sitemap and path in staged:
            s = re.sub(rf"(<loc>{re.escape(url)}</loc><lastmod>)[\d-]+(</lastmod>)", rf"\g<1>{TODAY}\g<2>", s)
    sitemap.write_text(s)


def bump_stylesheet_version(staged):
    """When styles.css changes, update ?v= on every page so browsers fetch the new file."""
    if "styles.css" not in staged:
        return []
    # A short fingerprint of the file's contents: changes whenever the styles change, even twice in a day
    version = hashlib.sha1((ROOT / "styles.css").read_bytes()).hexdigest()[:8]
    changed = []
    for path, _, _ in PAGES:
        f = ROOT / path
        s = f.read_text()
        new = re.sub(r'href="/styles\.css(\?v=[0-9a-f]+)?"', f'href="/styles.css?v={version}"', s)
        if new != s:
            f.write_text(new)
            changed.append(path)
    return changed


if __name__ == "__main__":
    staged = staged_files()
    for path in bump_stylesheet_version(staged):
        print(path)  # printed paths are staged by the pre-commit hook
        staged.add(path)
    update_readme(staged)
    update_sitemap(staged)
